import path from 'node:path';
import {fileURLToPath} from 'node:url';
import {parseArgs} from 'node:util';
import {mkdir,cp,readFile,writeFile,readdir,rm} from 'node:fs/promises';
import {httpOrigin} from '../public/connection-config.mjs';
import {contentSecurityPolicy} from '../server/origins.mjs';

const root=path.resolve(path.dirname(fileURLToPath(import.meta.url)),'..');
const marker='.rftg-static-build';
export async function buildStatic({outDir=path.join(root,'dist/static'),gatewayOrigin=''}={}){
  const origin=gatewayOrigin?httpOrigin(gatewayOrigin):'';
  const directory=path.resolve(outDir);
  await mkdir(directory,{recursive:true});
  const files=await readdir(directory);
  if(files.length&&!files.includes(marker))throw new Error(`输出目录非空，拒绝覆盖：${directory}`);
  for(const name of files)await rm(path.join(directory,name),{recursive:true,force:true});
  await cp(path.join(root,'public'),directory,{recursive:true});
  await cp(path.join(root,'shared'),path.join(directory,'shared'),{recursive:true});
  for(const name of ['LICENSE','LICENSE.assets-code','ASSET_LICENSES.md'])await cp(path.join(root,name),path.join(directory,name));
  await writeFile(path.join(directory,'client-config.json'),JSON.stringify({gatewayOrigin:origin},null,2)+'\n');
  const index=await readFile(path.join(directory,'index.html'),'utf8');
  const csp=contentSecurityPolicy(origin,true).replaceAll('&','&amp;').replaceAll('"','&quot;');
  await writeFile(path.join(directory,'index.html'),index.replace('<head>',`<head>\n  <meta http-equiv="Content-Security-Policy" content="${csp}">`));
  await writeFile(path.join(directory,marker),'Generated by scripts/build-static.mjs\n');
  return {directory,gatewayOrigin:origin};
}

if(process.argv[1]&&path.resolve(process.argv[1])===fileURLToPath(import.meta.url)){
  const {values}=parseArgs({options:{'gateway-origin':{type:'string'},out:{type:'string'}}});
  const built=await buildStatic({outDir:values.out,gatewayOrigin:values['gateway-origin']??process.env.GATEWAY_ORIGIN??''});
  console.log(`Static files: ${built.directory}\nGateway: ${built.gatewayOrigin||'same origin (local default)'}`);
}
